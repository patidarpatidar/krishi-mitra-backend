async function seedLivestockArticles() {
try {
if (!process.env.MONGODB_URI) {
throw new Error("MONGODB_URI is missing in .env");
}

await mongoose.connect(process.env.MONGODB_URI);
console.log("MongoDB connected");

for (const article of livestockArticles) {
  await LivestockArticle.findOneAndUpdate(
    { slug: article.slug },
    {
      $set: article,
      $setOnInsert: {
        viewsCount: 0,
        likesCount: 0,
      },
    },
    {
      upsert: true,
      new: true,
      runValidators: true,
      setDefaultsOnInsert: true,
    }
  );

  console.log(`Seeded: ${article.slug}`);
}

console.log("Livestock seed completed successfully");

} catch (error) {
console.error("Livestock seed failed:", error.message);
process.exitCode = 1;
} finally {
await mongoose.disconnect();
}
}

seedLivestockArticles();
